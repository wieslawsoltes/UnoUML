import assert from 'node:assert/strict';

export async function verifyTypedFields(page, source) {
  const paper = page.locator('.paper').first(), surface = page.locator('.surface').first();
  const editor = page.getByRole('textbox',{name:'Edit diagram label'});
  const yaml = '@startyaml\n{first: same, second: same, count: 42}\n@endyaml';
  await source.fill(yaml);
  const second = yaml.lastIndexOf('same');
  await paper.locator(`[data-edit-start="${second}"][data-edit-role="value"]`).dblclick();
  assert.equal(await editor.inputValue(),'same');
  await editor.fill('new: value');
  await editor.press('Enter');
  assert.equal(await source.inputValue(),yaml.slice(0,second)+'"new: value"'+yaml.slice(second+4));
  await paper.locator('[data-edit-role="value"]').filter({hasText:/^new: value$/}).waitFor();
  assert.equal(await paper.getAttribute('data-renderer'),'managed');
  await surface.press('Control+z');
  assert.equal(await source.inputValue(),yaml);

  const block = '@startyaml\nnote: >-  # retained comment\n  first line\n  second line\nnext: true\n@endyaml';
  await source.fill(block);
  await paper.locator('[data-edit-kind="yaml-block"]').dblclick();
  assert.equal(await editor.inputValue(),'first line second line');
  await editor.fill('Alpha\nBeta');
  await editor.press('Control+Enter');
  assert.equal(await source.inputValue(),block.replace('>-  # retained comment\n  first line\n  second line','"Alpha\\nBeta"  # retained comment'));
  await paper.locator('[data-edit-kind="yaml-double"]').filter({hasText:/Alpha/}).waitFor();
  await surface.press('Control+z');
  assert.equal(await source.inputValue(),block);

  const empty = '@startyaml\nempty: \n@endyaml';
  await source.fill(empty);
  await paper.locator('[data-edit-kind="yaml-string"][data-edit-length="0"]').dblclick();
  await editor.fill('Filled');
  await editor.press('Enter');
  assert.equal(await source.inputValue(),empty.replace('empty: ','empty: Filled'));
  await paper.locator('[data-edit-role="value"]').filter({hasText:/^Filled$/}).waitFor();

  const quotedEmpty = '@startyaml\nempty: ""\n@endyaml';
  await source.fill(quotedEmpty);
  await paper.locator('[data-edit-kind="yaml-double"][data-edit-role="value"]').dblclick();
  assert.equal(await editor.inputValue(),'');
  await editor.fill('Quoted value');
  await editor.press('Enter');
  assert.equal(await source.inputValue(),quotedEmpty.replace('""','"Quoted value"'));
  await paper.locator('[data-edit-kind="yaml-double"]').filter({hasText:'Quoted value'}).waitFor();

  const salt = '@startsalt\n{\n [Same] | [Same]\n "Input       " | []\n}\n@endsalt';
  await source.fill(salt);
  const secondButton = salt.lastIndexOf('Same');
  await paper.locator(`[data-edit-start="${secondButton}"]`).dblclick();
  await editor.fill('Updated');
  await editor.press('Enter');
  assert.equal(await source.inputValue(),salt.slice(0,secondButton)+'Updated'+salt.slice(secondButton+4));
  await paper.locator('.salt-button').filter({hasText:/Updated/}).waitFor();
  await surface.press('Control+z');
  assert.equal(await source.inputValue(),salt);
  await paper.locator('.salt-input').dblclick();
  assert.equal(await editor.inputValue(),'Input');
  await editor.fill('Account');
  await editor.press('Enter');
  assert.equal(await source.inputValue(),salt.replace('Input       ','Account       '));
  await paper.locator('.salt-input').filter({hasText:/Account/}).waitFor();
  assert.equal(await paper.getAttribute('data-renderer'),'managed');
  const chart = '@startchart\nh-axis [Same, Same]\nv-axis 0 --> 100\nbar "Completed" [20, 20]\nlegend right\n@endchart';
  await source.fill(chart);
  const category = chart.lastIndexOf('Same');
  await paper.locator(`[data-edit-start="${category}"]`).dblclick();
  await editor.fill('Later');
  await editor.press('Enter');
  assert.equal(await source.inputValue(),chart.slice(0,category)+'Later'+chart.slice(category+4));
  await paper.locator('[data-edit-kind="chart-category"]').filter({hasText:'Later'}).waitFor();
  const secondValue = (await source.inputValue()).lastIndexOf('20');
  await paper.locator(`rect[data-edit-start="${secondValue}"]`).dblclick();
  assert.equal(await editor.inputValue(),'20');
  await editor.fill('45');
  await editor.press('Enter');
  assert.match(await source.inputValue(),/\[20, 45\]/);
  await surface.press('Control+z');
  assert.match(await source.inputValue(),/\[20, 20\]/);
  const packet = '@startpacketdiag\n{\n 0-7: Same\n 8-15: Same\n}\n@endpacketdiag';
  await source.fill(packet);
  const packetAt = packet.lastIndexOf('Same');
  await paper.locator(`[data-edit-start="${packetAt}"][data-edit-kind="packet-label"]`).dblclick();
  await editor.fill('Flags');
  await editor.press('Enter');
  assert.equal(await source.inputValue(),packet.slice(0,packetAt)+'Flags'+packet.slice(packetAt+4));
  await paper.locator('[data-edit-kind="packet-label"]').filter({hasText:'Flags'}).waitFor();
  assert.equal(await paper.getAttribute('data-renderer'),'managed');
  const activity = '@startuml\nstart\n  #lightblue: First line\n    **Second line**  ; <<procedure>>\nstop\n@enduml';
  await source.fill(activity);
  await paper.locator('[data-edit-kind="activity-label"]').dblclick();
  assert.equal(await editor.inputValue(),'First line\n**Second line**');
  await editor.fill('Updated action\n**Next step**');
  await editor.press('Control+Enter');
  assert.equal(await source.inputValue(),activity.replace('First line\n    **Second line**','Updated action\n    **Next step**'));
  await paper.locator('[data-edit-kind="activity-label"]').filter({hasText:/Next step/}).waitFor();
  assert.equal(await paper.getAttribute('data-renderer'),'managed');
  await surface.press('Control+z');
  assert.equal(await source.inputValue(),activity);
  const timing = '@startuml\nrobust "Bus" as Bus\nconcise "Control" as Ctrl\n@0\nBus is Idle\nCtrl is Quiet\n@10\nBus is Busy\nCtrl is Ready\nCtrl -> Bus@+2 : Send\n@enduml';
  await source.fill(timing);
  await paper.locator(`[data-edit-start="${timing.indexOf('"Bus"')}"][data-edit-kind="quoted"]`).dblclick();
  await editor.fill('Data bus');
  await editor.press('Enter');
  assert.equal(await source.inputValue(),timing.replace('"Bus"','"Data bus"'));
  const currentTiming = await source.inputValue();
  await paper.locator(`[data-edit-start="${currentTiming.indexOf('Busy')}"][data-edit-role="value"]`).first().dblclick();
  assert.equal(await editor.inputValue(),'Busy');
  await editor.fill('Working now: ready');
  await editor.press('Enter');
  assert.match(await source.inputValue(),/Bus is "Working now: ready"/);
  await paper.locator('[data-edit-role="value"]').filter({hasText:'Working now: ready'}).first().waitFor();
  const messageAt = (await source.inputValue()).indexOf('Send');
  await paper.locator(`[data-edit-start="${messageAt}"]`).dblclick();
  await editor.fill('Dispatch');
  await editor.press('Enter');
  assert.match(await source.inputValue(),/Ctrl -> Bus@\+2 : Dispatch/);
  await paper.locator('.timing-message').filter({hasText:'Dispatch'}).waitFor();
  assert.equal(await paper.getAttribute('data-renderer'),'managed');
  console.log('Verified YAML flow/scalar/block/empty fields, Salt controls, chart data, packet labels, multiline activity actions and Timing captions/states/messages with atomic undo.');
}
