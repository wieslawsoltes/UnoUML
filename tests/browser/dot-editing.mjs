import { activateControl, fillControl } from './native-controls.mjs';
import assert from 'node:assert/strict';

export async function verifyDotEditing(page, source) {
  const paper = page.locator('.paper').first(), surface = page.locator('.surface').first();
  const editor = page.getByRole('textbox',{name:'Edit diagram label'});
  const node = id => paper.locator(`[data-dot-id="node:${id}"]`);
  const dot = '@startdot\ndigraph {\n  rankdir=LR;\n  a [label="Same",shape=box];\n  b [label="Same",shape=box];\n  c [label="Target",shape=box];\n  a -> b [label="Calls"];\n}\n@enddot';
  await fillControl(page, source, dot);
  await node('b').dblclick();
  assert.equal(await editor.inputValue(),'Same');
  await fillControl(page, editor, 'Changed');
  await editor.press('Enter');
  assert.equal(await source.inputValue(),dot.replace('b [label="Same"','b [label="Changed"'));
  await node('b').filter({hasText:'Changed'}).waitFor();
  await surface.press('Control+z');
  assert.equal(await source.inputValue(),dot);
  await activateControl(page, node('a'));
  await activateControl(page, page.getByRole('button',{name:'Connect selected object',exact:true}));
  await activateControl(page, node('c'));
  await page.waitForFunction(() => [...document.querySelectorAll('textarea')].some(el=>el.value.includes('a -> c;')));
  assert.match(await source.inputValue(),/a -> c;/);
  await surface.press('Control+z');
  assert.equal(await source.inputValue(),dot);
  const edge = paper.locator('[data-dot-id="edge:0"]');
  await activateControl(page, edge.locator('text').filter({hasText:'Calls'}));
  await activateControl(page, page.getByRole('button',{name:'Reattach target endpoint',exact:true}));
  await activateControl(page, node('c'));
  await page.waitForFunction(() => [...document.querySelectorAll('textarea')].some(el=>el.value.includes('a -> c [label="Calls"]')));
  assert.equal(await source.inputValue(),dot.replace('a -> b [label="Calls"]','a -> c [label="Calls"]'));
  await surface.press('Control+z');
  await edge.locator('text').filter({hasText:'Calls'}).dblclick();
  await fillControl(page, editor, 'Sends');
  await editor.press('Enter');
  assert.equal(await source.inputValue(),dot.replace('"Calls"','"Sends"'));
  await activateControl(page, edge.locator('text').filter({hasText:'Sends'}));
  await surface.press('Delete');
  assert.doesNotMatch(await source.inputValue(),/a -> b/);
  await surface.press('Control+z');
  assert.match(await source.inputValue(),/label="Sends"/);

  const implicit = '@startdot\ndigraph { "a\\\\path":port -> b; }\n@enddot';
  await fillControl(page, source, implicit);
  await paper.locator('[data-dot-kind="node"][data-dot-explicit="false"]').first().dblclick();
  await fillControl(page, editor, 'Visible');
  await editor.press('Enter');
  assert.match(await source.inputValue(),/"a\\\\path" \[label="Visible"\]/);
  await paper.locator('[data-dot-kind="node"]').filter({hasText:'Visible'}).waitFor();
  assert.equal(await paper.getAttribute('data-renderer'),'managed');

  const html = '@startdot\ndigraph { a [label=<<TABLE BORDER="1"><TR><TD PORT="left">Same</TD><TD>Same</TD></TR></TABLE>>]; }\n@enddot';
  await fillControl(page, source, html);
  const second = html.lastIndexOf('Same');
  await paper.locator(`[data-edit-start="${second}"][data-edit-kind="dot-html-text"]`).dblclick();
  assert.equal(await editor.inputValue(),'Same');
  await fillControl(page, editor, 'A & B');
  await editor.press('Enter');
  assert.equal(await source.inputValue(),html.slice(0,second)+'A &amp; B'+html.slice(second+4));
  await paper.locator('[data-edit-kind="dot-html-text"]').filter({hasText:'A & B'}).waitFor();
  await surface.press('Control+z');
  assert.equal(await source.inputValue(),html);
  const record = '@startdot\ndigraph { a [shape=record,label="{<p> Same|Same}"]; }\n@enddot';
  await fillControl(page, source, record);
  const recordAt = record.lastIndexOf('Same');
  await paper.locator(`[data-edit-start="${recordAt}"][data-edit-kind="dot-record-text"]`).dblclick();
  await fillControl(page, editor, 'New | field');
  await editor.press('Enter');
  assert.equal(await source.inputValue(),record.slice(0,recordAt)+'New \\| field'+record.slice(recordAt+4));
  await paper.locator('[data-edit-kind="dot-record-text"]').filter({hasText:'New | field'}).waitFor();
  assert.equal(await paper.getAttribute('data-renderer'),'managed');
  const strict = '@startdot\nstrict digraph { a -> b [label="First"]; a -> b [color=red]; c; }\n@enddot';
  await fillControl(page, source, strict);
  const merged = paper.locator('[data-dot-kind="edge"][data-dot-merged="true"]');
  await activateControl(page, merged.locator('text').filter({hasText:'First'}));
  await page.getByRole('button',{name:'Reattach target endpoint',exact:true}).waitFor({state:'visible'});
  await surface.press('Delete');
  await merged.waitFor({state:'detached'});
  assert.equal(await source.inputValue(),'@startdot\nstrict digraph { a ; b ;; a ; b ;; c; }\n@enddot');
  assert.equal(await paper.locator('[data-dot-kind="node"]').count(),3,'Deleting a strict edge preserves its endpoint nodes');
  await surface.press('Control+z');
  await merged.locator('text').filter({hasText:'First'}).waitFor();
  assert.equal(await source.inputValue(),strict,'One undo restores every strict-edge declaration');
  await merged.locator('text').filter({hasText:'First'}).dblclick();
  await fillControl(page, editor, 'Merged label');
  await editor.press('Enter');
  await merged.locator('text').filter({hasText:'Merged label'}).waitFor();
  assert.equal(await source.inputValue(),'@startdot\nstrict digraph { a ; b ;\n  a -> b [label="First"];; a ; b ;\n  a -> b [color=red, label="Merged label"];; c; }\n@enddot');
  assert.equal(await paper.locator('[data-dot-kind="edge"]').count(),1);
  const sharedStrict = '@startdot\nstrict digraph { a->b->c[label=Shared]; a->b[color=red]; b->c[color=blue]; }\n@enddot';
  await fillControl(page, source, sharedStrict);
  const firstShared = paper.locator('[data-dot-from-id="a"][data-dot-to-id="b"]');
  const secondShared = paper.locator('[data-dot-from-id="b"][data-dot-to-id="c"]');
  await firstShared.locator('text').filter({hasText:'Shared'}).dblclick();
  await fillControl(page, editor, 'Only AB');
  await editor.press('Enter');
  await firstShared.locator('text').filter({hasText:'Only AB'}).waitFor();
  await secondShared.locator('text').filter({hasText:'Shared'}).waitFor();
  assert.equal(await source.inputValue(),'@startdot\nstrict digraph { a;b;c;\n  a -> b [label=Shared];\n  b -> c [label=Shared];; a;b;\n  a -> b [color=red, label="Only AB"];; b->c[color=blue]; }\n@enddot',
    'The selected logical edge receives a final label override while its sibling retains the shared label');
  await surface.press('Control+z');
  assert.equal(await source.inputValue(),sharedStrict);
  const sharedHtml = sharedStrict.replace('label=Shared','label=<Shared <B>edge</B>>');
  await fillControl(page, source, sharedHtml);
  await firstShared.locator('text').filter({hasText:'edge'}).waitFor();
  assert.equal(await paper.locator('[data-dot-kind="edge"] [data-edit-start]').count(),0,
    'A shared HTML label cannot expose a token edit that changes other edges');
  await firstShared.locator('text').filter({hasText:'Shared'}).dblclick();
  assert.equal(await editor.count(),0);
  assert.equal(await source.inputValue(),sharedHtml);
  console.log('Verified DOT labels, escaped identities, implicit declarations, literal connection/retarget/delete handles, HTML/record cells and safe strict-merged edge editing.');
  await verifyDotStructure(page, source);
}

async function verifyDotStructure(page, source) {
  await page.setViewportSize({width:1390,height:860});
  const paper = page.locator('.paper').first(), surface = page.locator('.surface').first();
  const sourceAutomationId = await source.getAttribute('xamlautomationid');
  assert.ok(sourceAutomationId, 'The source editor exposes a stable public XAML identity');
  // Read-only observation follows semantic replacement while an owned modal
  // correctly excludes the source from the accessible interaction tree.
  const observedSource = page.locator('textarea[xamlautomationid=' + JSON.stringify(sourceAutomationId) + ']');
  const node = id => paper.locator(`[data-dot-id=${JSON.stringify('node:' + id)}]`);
  const load = async input => {
    const previous = await paper.locator('svg').elementHandle();
    await fillControl(page, source, input);
    if (previous) await page.waitForFunction(svg => !svg.isConnected, previous);
    await paper.locator('svg').waitFor();
    assert.equal(await paper.getAttribute('data-renderer'),'managed');
  };
  const pair = async (first, second) => {
    await activateControl(page, node(first));
    await activateControl(page, node(second), {modifiers:['Shift']});
    await page.getByText('DOT MULTIPLE SELECTION',{exact:true}).waitFor();
    assert.equal(await paper.locator('.multi-mark').count(),1);
    assert.equal(await page.getByRole('button',{name:'Connect selected object',exact:true}).isVisible(),false);
  };
  const sourceValue = async value => page.waitForFunction(expected => [...document.querySelectorAll('textarea')].some(input => input.value === expected),value);
  const original = '@startdot\ndigraph {\n node[shape=box,color=blue];\n a[label="Alpha"]; b[label="Beta"]; c[label="Outside"];\n a:out->b:in[label="Calls"]; a->c[label="External"];\n}\n@enddot';
  await load(original);
  await pair('a','b');
  await surface.press('Control+d');
  await node('aCopy').waitFor();
  await node('bCopy').waitFor();
  assert.equal(await paper.locator('[data-dot-kind="node"]').count(),5);
  assert.equal(await paper.locator('[data-dot-kind="edge"]').count(),3);
  assert.match(await source.inputValue(),/aCopy:out -> bCopy:in/);
  await surface.press('Control+z');
  await sourceValue(original);
  await node('aCopy').waitFor({state:'detached'});

  await pair('a','b');
  const beforeGroup = await source.inputValue();
  await surface.press('Control+g');
  const groupDialog = page.getByRole('dialog',{name:'Group selected DOT nodes',exact:true});
  await groupDialog.waitFor();
  await source.waitFor({state:'hidden'});
  // Native Uno exposes this single-line TextBox as an input. The source editor
  // remains a CSS-visible textarea behind the modal, so target the named field.
  const clusterLabel = groupDialog.getByRole('textbox',{name:'Cluster label',exact:true});
  assert.equal(await clusterLabel.inputValue(), 'Group');
  await fillControl(page, clusterLabel, 'Canvas group');
  assert.equal(await observedSource.inputValue(), beforeGroup, 'Typing the dialog label does not replace the document');
  await activateControl(page, groupDialog.getByRole('button', {name:'Group',exact:true}));
  const cluster = paper.locator('[data-dot-id="cluster:cluster_Group"]');
  await cluster.locator('text').filter({hasText:'Canvas group'}).waitFor();
  assert.match(await source.inputValue(),/label="Canvas group"/);
  await activateControl(page, cluster.locator('text').filter({hasText:'Canvas group'}));
  await page.getByRole('button',{name:'Ungroup cluster',exact:true}).waitFor();
  await surface.press('Control+Shift+g');
  await cluster.waitFor({state:'detached'});
  assert.equal(await paper.locator('[data-dot-kind="node"]').count(),3);
  assert.match(await source.inputValue(),/cluster=false/);
  await surface.press('Control+z');
  await cluster.waitFor();
  await surface.press('Control+z');
  await sourceValue(original);
  await cluster.waitFor({state:'detached'});

  await activateControl(page, node('a'));
  await surface.press('Delete');
  await node('a').waitFor({state:'detached'});
  assert.equal(await paper.locator('[data-dot-kind="node"]').count(),2);
  assert.equal(await paper.locator('[data-dot-kind="edge"]').count(),0);
  await surface.press('Control+z');
  await sourceValue(original);
  await node('a').waitFor();

  await pair('a','b');
  const copied = await surface.evaluate(element => {
    const clipboardData = new DataTransfer();
    element.dispatchEvent(new ClipboardEvent('copy',{clipboardData,bubbles:true,cancelable:true}));
    return clipboardData.getData('text/plain');
  });
  assert.match(copied,/^@startdot\ndigraph/);
  assert.match(copied,/a:out -> b:in/);
  assert.doesNotMatch(copied,/outside|External/);
  await surface.evaluate((element,text) => {
    const clipboardData = new DataTransfer(); clipboardData.setData('text/plain',text);
    element.dispatchEvent(new ClipboardEvent('paste',{clipboardData,bubbles:true,cancelable:true}));
  },copied);
  await node('a2').waitFor(); await node('b2').waitFor();
  assert.equal(await paper.locator('[data-dot-kind="edge"]').count(),3);
  await surface.press('Control+z');
  await sourceValue(original);
  await node('a2').waitFor({state:'detached'});

  const chain = '@startdot\ndigraph { node[color=blue]; a -> b -> c -> d [color=red,label="Chain"]; }\n@enddot';
  await load(chain);
  await activateControl(page, node('b')); await surface.press('Delete');
  await node('b').waitFor({state:'detached'});
  assert.equal(await paper.locator('[data-dot-kind="node"]').count(),3);
  assert.equal(await paper.locator('[data-dot-from-id="c"][data-dot-to-id="d"]').count(),1);
  assert.equal(await paper.locator('[data-dot-kind="edge"]').count(),1);
  assert.equal(await paper.getAttribute('data-renderer'),'managed');

  const sameLine = '@startdot\ndigraph { rankdir=LR; "a,b"[label="First"]; "x y"[label="Second"]; "a,b"->"x y"; }\n@enddot';
  await load(sameLine);
  await pair('a,b','x y');
  await surface.press('Control+d');
  await node('a,bCopy').waitFor(); await node('x yCopy').waitFor();
  await surface.press('Control+z');
  await sourceValue(sameLine);
  await node('a,bCopy').waitFor({state:'detached'});
  await surface.press('Escape');
  const bounds = await Promise.all([node('a,b').boundingBox(),node('x y').boundingBox()]);
  const left = Math.min(...bounds.map(box=>box.x))-8, top = Math.min(...bounds.map(box=>box.y))-8;
  const right = Math.max(...bounds.map(box=>box.x+box.width))+8, bottom = Math.max(...bounds.map(box=>box.y+box.height))+8;
  await page.keyboard.down('Shift');
  await page.mouse.move(left,top); await page.mouse.down(); await page.mouse.move(right,bottom,{steps:8}); await page.mouse.up();
  await page.keyboard.up('Shift');
  await page.getByText('DOT MULTIPLE SELECTION',{exact:true}).waitFor();
  assert.equal(await paper.locator('.multi-mark').count(),1);
  await surface.press('Delete');
  await node('a,b').waitFor({state:'detached'});
  await node('x y').waitFor({state:'detached'});
  await surface.press('Control+z');
  await sourceValue(sameLine);
  await node('a,b').waitFor();

  const product = '@startdot\ndigraph { subgraph cluster_left { a; } -> subgraph cluster_right { b; } [label="Product"]; }\n@enddot';
  await load(product);
  await activateControl(page, node('a'));
  assert.equal(await page.getByRole('button',{name:'Duplicate node',exact:true}).count(),0);
  await surface.press('Control+d');
  assert.equal(await source.inputValue(),product);
  await activateControl(page, node('a')); await surface.press('Delete');
  await node('a').waitFor({state:'detached'});
  assert.equal(await paper.locator('[data-dot-kind="edge"]').count(),0);
  await node('b').waitFor();
  console.log('Verified DOT multi-selection, node deletion across chains/products, scoped duplication, grouping/ungrouping, copy/paste with collision remapping, same-line escaped identities and marquee selection.');
}
